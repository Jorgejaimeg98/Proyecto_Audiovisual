        self.duracion_min = duracion_min
        self.genero = genero
        self.idioma_orig = idioma_orig
        self.pais_origen = pais_origen
        self.sinopsis = sinopsis
        self.clasificacion_edad = clasificion_edad
        self.fecha_agg = fecha_agg
